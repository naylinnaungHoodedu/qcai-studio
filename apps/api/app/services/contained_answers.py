"""Contained tutor and Q&A answers until the verified tutor exists (Decision D-19; plan task 1.11; AC-1-14).

A learner receives either an abstention or verbatim quotations of document spans from manifest-approved
public assets. Nothing generated by a provider, and no authored summary (video chapters, lesson notes),
is delivered as an answer. Quotations are matched to the question lexically, not verified, so grounded
is always false.

Phase 2 (AC-2-3): a citation is quoted only when the span registry verifies it: the span exists, its content
hash and source file equal the citation's, and its item is indexable (approved, bound, public plane). The
quotation is the span's own text, never the caller's excerpt, so a forged or tampered citation cannot put words
in a quotation. A schema-2 citation that fails verification is dropped and counted.
"""

from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Literal

from app.core.config import Settings, get_settings
from app.core.corpus_governance import CorpusRegistry
from app.schemas import Citation, GroundedClaim
from app.services.provenance import CITATION_SCHEMA, provisional_flag
from app.services.text_utils import truncate_display_excerpt

if TYPE_CHECKING:  # pragma: no cover
    from app.services.spans import SpanRecord, SpanRegistry

EXTRACTIVE_MODE = "extractive-lexically-screened"
MAX_QUOTED_SPANS = 3
ABSTENTION = (
    "I can't answer this from the approved course sources. Try naming a module, lesson or topic, "
    "for example routing, QUBO optimization or quantum kernels."
)
QUOTATION_LEAD = (
    "These passages from the approved course sources match your question. They are quoted as written; "
    "they have not been checked against your question, so read them as pointers, not as an answer:"
)


@dataclass(frozen=True)
class ContainedAnswer:
    answer: str
    decision: Literal["answer", "abstain"]
    reason: str
    citations: list[Citation] = field(default_factory=list)
    claims: list[GroundedClaim] = field(default_factory=list)
    grounded: bool = False
    dropped_unresolved: int = 0


def is_quotable(citation: Citation, registry: CorpusRegistry) -> bool:
    return (
        citation.source_kind == "document"
        and bool(citation.source_filename)
        and bool(citation.excerpt.strip())
        and registry.is_public_asset(citation.source_filename)
    )


def span_is_quotable(record: "SpanRecord", registry: CorpusRegistry) -> bool:
    """D-19 eligibility of a span record for the two-pass evidential pass (Phase 3 spec 4.4): exactly the spans
    contain_answer would quote. A test proves the two agree over every span of the dev and governed registries."""
    return (
        record.item_kind == "document"
        and record.plane == "public"
        and bool(record.source_filename)
        and registry.is_indexable(record.source_filename or "")
    )


def contain_answer(
    citations: list[Citation],
    registry: CorpusRegistry,
    spans: "SpanRegistry | None" = None,
    *,
    settings: Settings | None = None,
) -> ContainedAnswer:
    if spans is None:
        from app.services.store import get_course_store

        spans = get_course_store().span_registry
    settings = settings or get_settings()
    quoted: list[Citation] = []
    dropped = 0
    for citation in citations:
        if len(quoted) >= MAX_QUOTED_SPANS:
            break
        if not is_quotable(citation, registry):
            continue
        span = spans.get(citation.span_id or citation.chunk_id)
        if (
            span is None
            or span.content_hash != citation.content_hash
            or span.source_filename != citation.source_filename
            or not registry.is_indexable(span.source_filename or "")
        ):
            if citation.citation_schema == CITATION_SCHEMA:
                dropped += 1
            continue
        quoted.append(
            citation.model_copy(
                update={
                    "chunk_id": span.span_id,
                    "span_id": span.span_id,
                    "excerpt": truncate_display_excerpt(span.text, 320),
                    "content_hash": span.content_hash,
                    "item_id": span.item_id,
                    "item_version": span.item_version,
                    "start": span.start,
                    "end": span.end,
                    "citation_schema": CITATION_SCHEMA,
                    "resolution": "resolved",
                    "migration_status": citation.migration_status or "native",
                    "unresolved_reason": None,
                    "label": None,
                    "provisional": provisional_flag("resolved", settings),
                }
            )
        )
    if not quoted:
        return ContainedAnswer(answer=ABSTENTION, decision="abstain", reason="no_approved_span", dropped_unresolved=dropped)
    lines = [
        f'[{index}] "{" ".join(citation.excerpt.split())}" ({citation.source_title}, {citation.section_title})'
        for index, citation in enumerate(quoted, start=1)
    ]
    claims = [
        GroundedClaim(text=" ".join(citation.excerpt.split()), cited_span_ids=[citation.span_id], supported=True)
        for citation in quoted
    ]
    return ContainedAnswer(
        answer="\n".join([QUOTATION_LEAD, *lines]),
        decision="answer",
        reason="extractive_quotation_of_approved_spans",
        citations=quoted,
        claims=claims,
        dropped_unresolved=dropped,
    )
