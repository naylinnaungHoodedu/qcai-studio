"""Contained tutor and Q&A answers until the verified tutor exists (Decision D-19; plan task 1.11; AC-1-14).

A learner receives either an abstention or verbatim quotations of document spans from manifest-approved
public assets. Nothing generated by a provider, and no authored summary (video chapters, lesson notes),
is delivered as an answer. Quotations are matched to the question lexically, not verified, so grounded
is always false.
"""

from dataclasses import dataclass, field
from typing import Literal

from app.core.corpus_governance import CorpusRegistry
from app.schemas import Citation, GroundedClaim

EXTRACTIVE_MODE = "extractive-lexically-screened"
MAX_QUOTED_SPANS = 3
ABSTENTION = (
    "I can't answer this from the approved course sources. Try naming a module, lesson or topic, "
    "for example routing, QUBO optimization or quantum kernels."
)
QUOTATION_LEAD = (
    "These passages from the approved course sources match your question. They are quoted as written; "
    "they have not been checked against your question, so read them as pointers, not as an answer:"
)


@dataclass(frozen=True)
class ContainedAnswer:
    answer: str
    decision: Literal["answer", "abstain"]
    reason: str
    citations: list[Citation] = field(default_factory=list)
    claims: list[GroundedClaim] = field(default_factory=list)
    grounded: bool = False


def is_quotable(citation: Citation, registry: CorpusRegistry) -> bool:
    return (
        citation.source_kind == "document"
        and bool(citation.source_filename)
        and bool(citation.excerpt.strip())
        and registry.is_public_asset(citation.source_filename)
    )


def contain_answer(citations: list[Citation], registry: CorpusRegistry) -> ContainedAnswer:
    quoted = [citation for citation in citations if is_quotable(citation, registry)][:MAX_QUOTED_SPANS]
    if not quoted:
        return ContainedAnswer(answer=ABSTENTION, decision="abstain", reason="no_approved_span")
    lines = [
        f'[{index}] "{" ".join(citation.excerpt.split())}" ({citation.source_title}, {citation.section_title})'
        for index, citation in enumerate(quoted, start=1)
    ]
    claims = [
        GroundedClaim(text=" ".join(citation.excerpt.split()), cited_span_ids=[citation.span_id or citation.chunk_id], supported=True)
        for citation in quoted
    ]
    return ContainedAnswer(
        answer="\n".join([QUOTATION_LEAD, *lines]),
        decision="answer",
        reason="extractive_quotation_of_approved_spans",
        citations=quoted,
        claims=claims,
    )
